android {
    namespace = "app.fireremote.phone"
    compileSdk = 36

    defaultConfig {
        applicationId = "app.fireremote.phone"
        minSdk = 26
        targetSdk = 36
        versionCode = 6
        versionName = "1.4"
    }

    // Release key: keystore.properties next to settings.gradle.kts (gitignored), with
    // storeFile (relative to this folder), storePassword, keyAlias, keyPassword.
    // Without it, release builds are signed with the debug key.
    // Keep your key: Android only installs an update over the app if it is signed with the same key.
    val keystoreProps = rootProject.file("keystore.properties")
    signingConfigs {
        if (keystoreProps.exists()) {
            val p = Properties().apply { keystoreProps.inputStream().use { load(it) } }
            create("release") {
                storeFile = rootProject.file(p.getProperty("storeFile"))
                storePassword = p.getProperty("storePassword")
                keyAlias = p.getProperty("keyAlias")
                keyPassword = p.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
}

